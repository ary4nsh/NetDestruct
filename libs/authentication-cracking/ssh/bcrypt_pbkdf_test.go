package ssh

import (
	"bytes"
	"testing"
)

func TestBcryptPBKDFGolden(t *testing.T) {
	// OpenBSD / golang.org/x/crypto/ssh/internal/bcrypt_pbkdf golden vector.
	want := []byte{
		0x1a, 0xe4, 0x2c, 0x05, 0xd4, 0x87, 0xbc, 0x02, 0xf6,
		0x49, 0x21, 0xa4, 0xeb, 0xe4, 0xea, 0x93, 0xbc, 0xac,
		0xfe, 0x13, 0x5f, 0xda, 0x99, 0x97, 0x4c, 0x06, 0xb7,
		0xb0, 0x1f, 0xae, 0x14, 0x9a,
	}
	got := make([]byte, len(want))
	if err := bcryptPBKDF([]byte("password"), []byte("salt"), got, 12); err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) {
		t.Fatalf("got %x\nwant %x", got, want)
	}
}
